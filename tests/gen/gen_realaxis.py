#!/usr/bin/env python3
"""Generate tests/realaxis_refs.inc: mpmath real-axis references for the C++17
special math functions, in the std:: conventions (no Condon-Shortley phase in
assoc_legendre; ellint_1/2/3 take the modulus k; ellint_3 uses (1 - nu sin^2)).
The inputs are those of the std:: comparison tests (with inexact decimals replaced
by nearby binary fractions), so libc++ builds get the same real-axis coverage.
Usage: python3 tests/gen/gen_realaxis.py > tests/realaxis_refs.inc"""
import mpmath as mp
mp.mp.dps = 40
rows = []
def add(fn, p1, p2, p3, x, v):
    rows.append((fn, p1, p2, p3, x, mp.mpf(v)))
X = [0.375, 1.5, 4.25, 9.75]
NU = [0, 0.5, 1.25, 3]
for x in X:
    for nu in NU:
        add('cyl_bessel_j', nu, 0, 0, x, mp.besselj(nu, x))
        add('cyl_neumann', nu, 0, 0, x, mp.bessely(nu, x))
        add('cyl_bessel_i', nu, 0, 0, x, mp.besseli(nu, x))
        add('cyl_bessel_k', nu, 0, 0, x, mp.besselk(nu, x))
    for n in (0, 1, 4):
        sj = mp.sqrt(mp.pi / (2 * x))
        add('sph_bessel', n, 0, 0, x, sj * mp.besselj(n + 0.5, x))
        add('sph_neumann', n, 0, 0, x, sj * mp.bessely(n + 0.5, x))
        add('hermite', n + 2, 0, 0, x, mp.hermite(n + 2, x))
        add('laguerre', n + 2, 0, 0, x, mp.laguerre(n + 2, 0, x))
        add('assoc_laguerre', n + 2, 3, 0, x, mp.laguerre(n + 2, 3, x))
    add('expint', 0, 0, 0, x, mp.ei(x))
    add('expint', 0, 0, 0, -x, mp.ei(-x))
    k = mp.mpf(0.625)
    add('ellint_1', 0.625, 0, 0, x, mp.ellipf(x, k * k))
    add('ellint_2', 0.625, 0, 0, x, mp.ellipe(x, k * k))
for c in (-0.875, -0.25, 0.125, 0.75):
    for l in (0, 1, 2, 5, 9):
        add('legendre', l, 0, 0, c, mp.legendre(l, c))
        for m in range(0, min(l, 3) + 1):
            add('assoc_legendre', l, m, 0, c, (-1) ** m * mp.legenp(l, m, c))
            th = mp.mpf(c) + 1
            add('sph_legendre', l, m, 0, c + 1, mp.re(mp.spherharm(l, m, th, 0)))
    m = mp.mpf(c) ** 2
    add('comp_ellint_1', 0, 0, 0, c, mp.ellipk(m))
    add('comp_ellint_2', 0, 0, 0, c, mp.ellipe(m))
    # std::comp_ellint_3(k = 0.5, nu = c), std::ellint_3(k = 0.5, nu = c, phi = 1.25)
    add('comp_ellint_3', 0.5, 0, 0, c, mp.ellippi(c, mp.mpf(0.25)))
    add('ellint_3', 0.5, 1.25, 0, c, mp.ellippi(c, 1.25, mp.mpf(0.25)))
    add('riemann_zeta', 0, 0, 0, 2.5 + c, mp.zeta(2.5 + c))
for x in (-7.5, -2.5, -0.75, 0.25, 0.5, 0.9990234375, 1.5, 2, 3.5, 12):
    add('riemann_zeta', 0, 0, 0, x, mp.zeta(x))
for a, b in ((0.5, 0.5), (2, 3), (1.25, 7.5), (10, 0.125)):
    add('beta', b, 0, 0, a, mp.beta(a, b))
for n in (0, 1, 2, 7, 20):
    for x in (0.0078125, 0.5, 1, 3.75, 10, 40):
        add('cyl_bessel_j_int', n, 0, 0, x, mp.besselj(n, x))
        add('cyl_bessel_i_int', n, 0, 0, x, mp.besseli(n, x))
print('// Generated by tests/gen/gen_realaxis.py (mpmath, 40 digits). Do not edit.')
for fn, p1, p2, p3, x, v in rows:
    print(f'    {{"{fn}", {float(p1)!r}L, {float(p2)!r}L, {float(p3)!r}L, {float(x)!r}L, {mp.nstr(v, 36, min_fixed=-5, max_fixed=5)}L}},')
