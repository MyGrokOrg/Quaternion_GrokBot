namespace {
template <class T> void vs_std() {
#if HAVE_STD_SPECIAL_MATH && !defined(_LIBCPP_VERSION)
    using W = quat::detail::sf::work_t<T>;
    // libstdc++ float special functions are computed in float; compare with the W versions.
    const T tol = std::is_same_v<T, float> ? T(2e-6) : rtol<T>(T(2e4));
    auto R = [](W v) { return quaternion<T>(static_cast<T>(v)); };
    const T xs[] = {T(0.375), T(1.5), T(4.25), T(9.75)};
    const T nus[] = {T(0), T(0.5), T(1.25), T(3)};
    for (T x : xs) {
        const quaternion<T> q(x);
        const W wx = static_cast<W>(x);
        for (T nu : nus) {
            const W wn = static_cast<W>(nu);
            CHECK_CLOSE(quat::cyl_bessel_j(nu, q), R(std::cyl_bessel_j(wn, wx)), tol);
            CHECK_CLOSE(quat::cyl_neumann(nu, q), R(std::cyl_neumann(wn, wx)), tol);
            CHECK_CLOSE(quat::cyl_bessel_i(nu, q), R(std::cyl_bessel_i(wn, wx)), tol);
            CHECK_CLOSE(quat::cyl_bessel_k(nu, q), R(std::cyl_bessel_k(wn, wx)), tol);
        }
        for (unsigned n : {0u, 1u, 4u}) {
            CHECK_CLOSE(quat::sph_bessel(n, q), R(std::sph_bessel(n, wx)), tol);
            CHECK_CLOSE(quat::sph_neumann(n, q), R(std::sph_neumann(n, wx)), tol);
            CHECK_CLOSE_S(quat::hermite(n + 2, q), R(std::hermite(n + 2, wx)), tol, T(1));
            CHECK_CLOSE_S(quat::laguerre(n + 2, q), R(std::laguerre(n + 2, wx)), tol, T(1));
            CHECK_CLOSE_S(quat::assoc_laguerre(n + 2, 3u, q), R(std::assoc_laguerre(n + 2, 3u, wx)), tol, T(1));
        }
        CHECK_CLOSE(quat::expint(q), R(std::expint(wx)), tol);
        CHECK_CLOSE(quat::expint(quaternion<T>(-x)), R(std::expint(-wx)), tol);
        CHECK_CLOSE(quat::ellint_1(T(0.625), q), R(std::ellint_1(W(0.625), wx)), tol);
        CHECK_CLOSE(quat::ellint_2(T(0.625), q), R(std::ellint_2(W(0.625), wx)), tol);
    }
    const T cs[] = {T(-0.875), T(-0.25), T(0.125), T(0.75)};
    for (T c : cs) {
        const quaternion<T> q(c);
        const W wc = static_cast<W>(c);
        for (unsigned l : {0u, 1u, 2u, 5u, 9u}) {
            CHECK_CLOSE_S(quat::legendre(l, q), R(std::legendre(l, wc)), tol, T(1));
            for (unsigned m = 0; m <= std::min(l, 3u); ++m) {
                CHECK_CLOSE_S(quat::assoc_legendre(l, m, q), R(std::assoc_legendre(l, m, wc)), tol, T(1));
                CHECK_CLOSE_S(quat::sph_legendre(l, m, quaternion<T>(c + 1)), R(std::sph_legendre(l, m, wc + 1)), tol, T(1));
            }
        }
        CHECK_CLOSE(quat::comp_ellint_1(q), R(std::comp_ellint_1(wc)), tol);
        CHECK_CLOSE(quat::comp_ellint_2(q), R(std::comp_ellint_2(wc)), tol);
        CHECK_CLOSE(quat::comp_ellint_3(T(0.5), q), R(std::comp_ellint_3(W(0.5), wc)), tol);
        CHECK_CLOSE(quat::ellint_3(T(0.5), q, T(1.25)), R(std::ellint_3(W(0.5), wc, W(1.25))), tol);
        CHECK_CLOSE(quat::hurwitz_zeta(quaternion<T>(T(2.5) + c), T(1)), R(std::riemann_zeta(W(2.5) + wc)), tol);
    }
#endif
}

template <class T> void identities() {
    const T tol = rtol<T>(T(4000));
    const T pi = quat::detail::pi_v<T>;
    const quaternion<T> qs[] = {on_axis(T(0.75), T(0.5)), on_axis(T(-1.25), T(1.5)), on_axis(T(2.5), T(0.25)),
                                on_axis(T(0.125), T(3))};
    for (const auto& q : qs) {
        // Bessel: Wronskian J_nu Y_{nu+1} - J_{nu+1} Y_nu = -2/(pi q), recurrence, half-integer order
        for (T nu : {T(0.25), T(1.5), T(-0.75)}) {
            const auto j0 = quat::cyl_bessel_j(nu, q), j1 = quat::cyl_bessel_j(nu + 1, q);
            const auto jm = quat::cyl_bessel_j(nu - 1, q);
            const auto y0 = quat::cyl_neumann(nu, q), y1 = quat::cyl_neumann(nu + 1, q);
            CHECK_CLOSE_S(j0 * y1 - j1 * y0, -T(2) / (pi * q), tol, abs(j0 * y1));
            CHECK_CLOSE_S(jm + j1, T(2) * nu / q * j0, tol, abs(jm) + abs(j1));
            const auto i0 = quat::cyl_bessel_i(nu, q), i1 = quat::cyl_bessel_i(nu + 1, q);
            const auto k0 = quat::cyl_bessel_k(nu, q), k1 = quat::cyl_bessel_k(nu + 1, q);
            CHECK_CLOSE_S(i0 * k1 + i1 * k0, inverse(q), tol, abs(i0 * k1));
            CHECK_CLOSE_S(quat::cyl_hankel_1(nu, q) + quat::cyl_hankel_2(nu, q), T(2) * j0, tol, abs(y0) + abs(j0));
        }
        CHECK_CLOSE(quat::cyl_bessel_j(T(0.5), q), sqrt(T(2) / (pi * q)) * sin(q), tol);
        CHECK_CLOSE(quat::cyl_bessel_j(T(2), q), quat::cyl_bessel_j(2, q), tol);
        CHECK_CLOSE(quat::sph_bessel(0u, q), sin(q) / q, tol);
        CHECK_CLOSE(quat::sph_neumann(0u, q), -cos(q) / q, tol);
        // Chebyshev and Legendre
        for (unsigned n : {0u, 1u, 3u, 7u}) {
            CHECK_CLOSE_S(quat::chebyshev_t(n, cos(q)), cos(T(n) * q), tol, abs(cos(T(n) * q)) + T(1));
            CHECK_CLOSE_S(quat::chebyshev_u(n, cos(q)) * sin(q), sin(T(n + 1) * q), tol, abs(sin(T(n + 1) * q)) + T(1));
            CHECK_CLOSE_S(quat::assoc_legendre(n, 0u, q), quat::legendre(n, q), tol, T(1));
            CHECK_CLOSE_S(quat::hermite(n + 1, q), T(2) * q * quat::hermite(n, q) - T(2 * n) * quat::hermite(n > 0 ? n - 1 : 0, q) * T(n > 0),
                          tol, abs(quat::hermite(n + 1, q)) + T(1));
        }
        // exponential/sine/cosine integrals
        // E_{n+1}(q) = (e^{-q} - q E_n(q)) / n
        for (unsigned n : {1u, 2u, 4u})
            CHECK_CLOSE_S(quat::expint(n + 1, q), (exp(-q) - q * quat::expint(n, q)) / T(n), tol,
                          abs(exp(-q)) + abs(q * quat::expint(n, q)));
        CHECK_CLOSE_S(quat::sinint(-q), -quat::sinint(q), tol, abs(quat::sinint(q)));
        CHECK_CLOSE_S(quat::fresnel_s(-q), -quat::fresnel_s(q), tol, abs(quat::fresnel_s(q)));
        CHECK_CLOSE_S(quat::fresnel_c(-q), -quat::fresnel_c(q), tol, abs(quat::fresnel_c(q)));
        // polygamma recurrence psi^(m)(q+1) = psi^(m)(q) + (-1)^m m! / q^(m+1)
        CHECK_CLOSE_S(quat::trigamma(q + T(1)), quat::trigamma(q) - inverse(q * q), tol, abs(quat::trigamma(q)));
        CHECK_CLOSE_S(quat::polygamma(2u, q + T(1)), quat::polygamma(2u, q) + T(2) * inverse(q * q * q), tol,
                      abs(quat::polygamma(2u, q)));
        CHECK_CLOSE(quat::polygamma(0u, q), quat::digamma(q), tol);
        // Hurwitz zeta: zeta(s, a) = zeta(s, a+1) + a^{-s}; zeta(s, 1) = zeta(s)
        CHECK_CLOSE(quat::hurwitz_zeta(q + T(2), T(1)), quat::riemann_zeta(q + T(2)), tol);
        CHECK_CLOSE_S(quat::hurwitz_zeta(q + T(2), T(0.5)), quat::hurwitz_zeta(q + T(2), T(1.5)) + exp(-(q + T(2)) * std::log(T(0.5))),
                      tol, abs(quat::hurwitz_zeta(q + T(2), T(1.5))));
        // polylog: Li_1(q) = -log(1-q), Li_0 = q/(1-q), Li_2 reflection
        CHECK_CLOSE(quat::polylog(1, q), -log(T(1) - q), tol);
        CHECK_CLOSE(quat::polylog(0, q), q / (T(1) - q), tol);
        CHECK_CLOSE_S(quat::polylog(2, q) + quat::polylog(2, T(1) - q), pi * pi / 6 - log(q) * log(T(1) - q), tol,
                      abs(quat::polylog(2, q)) + T(1));
        // Lambert W: W e^W = q on every branch
        for (int k : {0, -1, 1, 3}) {
            const auto w = quat::lambert_w(k, q);
            CHECK_CLOSE(w * exp(w), q, tol);
        }
        // incomplete gamma: lower + upper = Gamma, P + Q = 1, recurrence in a
        for (T a : {T(0.5), T(2.25), T(6)}) {
            CHECK_CLOSE_S(quat::tgamma_lower(a, q) + quat::tgamma_upper(a, q), quaternion<T>(std::tgamma(a)), tol,
                          abs(quat::tgamma_lower(a, q)) + std::tgamma(a));
            CHECK_CLOSE_S(quat::gamma_p(a, q) + quat::gamma_q(a, q), quaternion<T>(1), tol, abs(quat::gamma_p(a, q)) + 1);
            CHECK_CLOSE_S(quat::tgamma_upper(a + 1, q), a * quat::tgamma_upper(a, q) + exp(a * log(q) - q), tol,
                          abs(quat::tgamma_upper(a + 1, q)) + abs(a * quat::tgamma_upper(a, q)));
        }
        CHECK_CLOSE(quat::tgamma_upper(T(0), q), quat::expint(1u, q), tol);
        // elliptic: amplitude pi/2 gives the complete integrals
        CHECK_CLOSE(quat::ellint_1(T(0.5), quaternion<T>(pi / 2)), quat::comp_ellint_1(quaternion<T>(T(0.5))), tol);
        CHECK_CLOSE(quat::ellint_3(T(0.5), q, pi / 2), quat::comp_ellint_3(T(0.5), q), tol);
        CHECK_CLOSE_S(quat::ellint_1(T(0.5), q + pi), quat::ellint_1(T(0.5), q) + T(2) * quat::comp_ellint_1(quaternion<T>(T(0.5))),
                      tol, abs(quat::ellint_1(T(0.5), q + pi)));
        // incomplete beta: I_x(a, b) + I_{1-x}(b, a) = 1
        const auto x = q / T(4);
        CHECK_CLOSE_S(quat::ibeta(T(2.5), T(1.5), x) + quat::ibeta(T(1.5), T(2.5), T(1) - x), quaternion<T>(1), tol,
                      abs(quat::ibeta(T(2.5), T(1.5), x)) + 1);
        CHECK_CLOSE_S(quat::ibeta(T(2.5), T(1.5), x) + quat::ibetac(T(2.5), T(1.5), x), quaternion<T>(1), tol,
                      abs(quat::ibeta(T(2.5), T(1.5), x)) + 1);
    }
    // Airy at zero, Lambert W special values, Bessel/Ei at zero
    CHECK_NEAR(quat::airy_ai(quaternion<T>()).w(), T(0.355028053887817239260063186004183176L), tol);
    CHECK_NEAR(quat::airy_bi(quaternion<T>()).w(), T(0.614926627446000735150922369093613554L), tol);
    CHECK_NEAR(quat::lambert_w(quaternion<T>(std::exp(T(1)))).w(), T(1), tol);
    CHECK_NEAR(quat::lambert_w(-1, quaternion<T>(-std::exp(T(-1)))).w(), T(-1), T(1e-3));
    CHECK(quat::cyl_bessel_j(T(0.5), quaternion<T>()) == quaternion<T>());
    CHECK(quat::cyl_bessel_i(T(0), quaternion<T>()) == quaternion<T>(1));
    // Airy connection Ai(z) + w Ai(w z) + w^2 Ai(w^2 z) = 0 on the i axis (w = e^{2 pi i/3})
    {
        const quaternion<T> i(T(0), T(1), T(0), T(0));
        const quaternion<T> w = exp(i * (T(2) * pi / 3)), z = quaternion<T>(T(0.75), T(0.5), T(0), T(0));
        const auto s = quat::airy_ai(z) + w * quat::airy_ai(w * z) + w * w * quat::airy_ai(w * w * z);
        CHECK(abs(s) <= tol * abs(quat::airy_ai(z)) * 4);
        const auto b = quat::airy_bi(z), a = quat::airy_ai(z), aw = quat::airy_ai(w * w * z);
        // Bi(z) = e^{i pi/6} Ai(z e^{2 pi i/3}) + e^{-i pi/6} Ai(z e^{-2 pi i/3})   (DLMF 9.2.10)
        const auto bi = exp(i * (pi / 6)) * quat::airy_ai(w * z) + exp(-i * (pi / 6)) * aw;
        CHECK_CLOSE_S(b, bi, tol, abs(a) + abs(b));
    }
}
}  // namespace

