template <class T> void bessel_near_zeros() {
    if constexpr (std::is_same_v<T, float>) return;  // inputs are doubles
    using Q = quaternion<T>;
    const T e = std::numeric_limits<T>::epsilon();
    double worst_rel = 0, worst_abs = 0, worst_k = 0;
    for (const auto& r : bessel_zero_refs) {
        const Q q(static_cast<T>(r.x), static_cast<T>(r.y), T(), T());
        const Q want(static_cast<T>(r.re), static_cast<T>(r.im), T(), T());
        const Q got = quat::cyl_bessel_j(static_cast<T>(r.nu), q);
        const T err = abs(got - want);
        if (abs(want) > T(1e-14)) {
            const double rel = static_cast<double>(err / abs(want) / e);
            worst_rel = std::max(worst_rel, rel);
            qtest::check(rel <= 32, "J near a zero: relative error");
        } else {
            worst_abs = std::max(worst_abs, static_cast<double>(err));
            qtest::check(err <= e * T(1e-6), "J at a rounded zero: absolute error");
        }
        if (r.nu == std::floor(r.nu)) {
            const Q gi = quat::cyl_bessel_j(static_cast<int>(r.nu), q);
            qtest::check(abs(gi - got) <= T(4) * e * std::max(abs(want), e * T(1e-6)), "J integer order");
        }
    }
    for (const auto& r : bessel_k_small_refs) {
        const Q q(static_cast<T>(r.x), static_cast<T>(r.y), T(), T());
        const Q want(static_cast<T>(r.re), static_cast<T>(r.im), T(), T());
        const double rel = static_cast<double>(abs(quat::cyl_bessel_k(static_cast<T>(r.nu), q) - want) / abs(want) / e);
        worst_k = std::max(worst_k, rel);
        qtest::check(rel <= 48, "K small |w|");
    }
    std::printf("  [%s] J near zeros: worst %.3g eps relative, %.3g absolute at rounded zeros; K small |w|: %.3g eps\n",
                qtest::current_type, worst_rel, worst_abs, worst_k);
}
