template <class T> void hurwitz_large_im() {
    const T e = std::numeric_limits<T>::epsilon();
    double worst = 0;
    for (const auto& r : refs4) {
        const quaternion<T> q(static_cast<T>(r.re), static_cast<T>(r.im), T(), T());
        const quaternion<T> want(static_cast<T>(r.wre), static_cast<T>(r.wim), T(), T());
        const quaternion<T> got = quat::hurwitz_zeta(q, static_cast<T>(r.p));
        const T sabs = std::hypot(static_cast<T>(r.re), static_cast<T>(r.im));
        const T tol = std::is_same_v<T, float> ? T(4) * e : T(16) * e * std::max(T(1), sabs);
        worst = std::max(worst, static_cast<double>(abs(got - want) / abs(want) / (e * std::max(T(1), sabs))));
        qtest::check(close(got, want, tol), "hurwitz_zeta strip/large Im s");
    }
    std::printf("  [%s] hurwitz large |Im s|: worst error %.3g |s| eps\n", qtest::current_type, worst);
}
