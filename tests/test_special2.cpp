template <class T>
quaternion<T> eval2(std::string_view f, T a, T b, const quaternion<T>& q) {
    using namespace quat;
    const auto n = static_cast<unsigned>(a);
    const auto k = static_cast<int>(a);
    if (f == "cyl_bessel_j") return cyl_bessel_j(a, q);
    if (f == "cyl_neumann") return cyl_neumann(a, q);
    if (f == "cyl_bessel_i") return cyl_bessel_i(a, q);
    if (f == "cyl_bessel_k") return cyl_bessel_k(a, q);
    if (f == "cyl_hankel_1") return cyl_hankel_1(a, q);
    if (f == "cyl_hankel_2") return cyl_hankel_2(a, q);
    if (f == "sph_bessel") return sph_bessel(n, q);
    if (f == "sph_neumann") return sph_neumann(n, q);
    if (f == "airy_ai") return airy_ai(q);
    if (f == "airy_bi") return airy_bi(q);
    if (f == "expint") return expint(q);
    if (f == "expint_n") return expint(n, q);
    if (f == "sinint") return sinint(q);
    if (f == "cosint") return cosint(q);
    if (f == "fresnel_s") return fresnel_s(q);
    if (f == "fresnel_c") return fresnel_c(q);
    if (f == "polygamma") return polygamma(n, q);
    if (f == "hurwitz_zeta") return hurwitz_zeta(q, a);
    if (f == "polylog") return polylog(a, q);
    if (f == "lambert_w") return lambert_w(k, q);
    if (f == "tgamma_upper") return tgamma_upper(a, q);
    if (f == "tgamma_lower") return tgamma_lower(a, q);
    if (f == "comp_ellint_1") return comp_ellint_1(q);
    if (f == "comp_ellint_2") return comp_ellint_2(q);
    if (f == "comp_ellint_3") return comp_ellint_3(a, q);
    if (f == "ellint_1") return ellint_1(a, q);
    if (f == "ellint_2") return ellint_2(a, q);
    if (f == "ellint_3") return ellint_3(a, q, b);
    if (f == "ibeta") return ibeta(a, b, q);
    return quaternion<T>(std::numeric_limits<T>::quiet_NaN());
}

template <class T> void reference_values() {
    const T tol = std::is_same_v<T, float> ? T(4e-6) : rtol<T>(T(400));
    for (const auto& r : refs2) {
        const T a = static_cast<T>(r.p1), b = static_cast<T>(r.p2);
        const auto want_c = std::complex<T>(static_cast<T>(r.wre), static_cast<T>(r.wim));
        if (!std::isfinite(want_c.real()) || std::abs(want_c) > std::numeric_limits<T>::max() / 4 ||
            std::abs(want_c) < std::numeric_limits<T>::min() * 1e6) continue;
        if (r.im == 0) {
            const quaternion<T> got = eval2(r.fn, a, b, quaternion<T>(static_cast<T>(r.re)));
            const quaternion<T> want(want_c.real(), want_c.imag(), T(), T());
            qtest::check(close(got, want, tol), r.fn.data());
        } else {
            const quaternion<T> q = on_axis(static_cast<T>(r.re), static_cast<T>(r.im));
            const quaternion<T> got = eval2(r.fn, a, b, q);
            const quaternion<T> want = on_axis(want_c.real(), want_c.imag());
            qtest::check(close(got, want, tol), r.fn.data());
            // the lift commutes with conjugation of the vector part
            const quaternion<T> gc = eval2(r.fn, a, b, conj(q));
            CHECK(close(gc, conj(got), tol, abs(got)));
        }
    }
}
